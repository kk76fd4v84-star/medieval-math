#!/usr/bin/env python3
"""Write src/config/asset_sizes.js (image + audio path -> bytes) for the loading bar. Usage: asset_sizes.py <game root>"""
import os, sys, json
root = sys.argv[1] if len(sys.argv) > 1 else "."
out = {}
for d, _, fs in os.walk(os.path.join(root, "assets")):
    for f in fs:
        if f.lower().endswith((".png", ".webp", ".jpg", ".jpeg", ".mp3", ".ogg", ".m4a", ".wav")):  # v12r: audio too (music preloads with the bar)
            p = os.path.join(d, f); out[os.path.relpath(p, root).replace(os.sep, "/")] = os.path.getsize(p)
with open(os.path.join(root, "src/config/asset_sizes.js"), "w") as fh:
    fh.write("// generated by tools/asset_sizes.py (km_site_deploy.sh): image + audio bytes for the loading bar (KM.Loader)\nwindow.KM_ASSET_SIZES = " + json.dumps(out, separators=(",", ":"), sort_keys=True) + ";\n")
print(len(out), "files")
