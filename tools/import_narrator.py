#!/usr/bin/env python3
"""Magnus's narrator (incoming/magnus_art/narrator_skeleton_rock.png): orange-hooded skeleton leaning on his rock.
The source already has an alpha channel, but its "opaque" pixels sit at alpha 252-253 (slightly see-through) and there is
a wide empty margin. Extract: alpha rescaled so the body is fully opaque (a * 255 / 253, clamped; antialiased edges keep
their ramp), RGB untouched (never repainted), cropped to the opaque bbox + 4 px. Pivot = bottom centre of the lowest
opaque row (the rock's base stands ON the ground line). Writes assets/v20/narrator_skeleton_rock.png + src/config/narrator.js."""
import json, os
import numpy as np
from PIL import Image
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(R, "incoming/magnus_art/narrator_skeleton_rock.png")
im = np.array(Image.open(src).convert("RGBA")).astype(np.int32)
a = im[..., 3]; a2 = np.clip(a * 255 // 253, 0, 255); im[..., 3] = a2
ys, xs = np.where(a2 > 20); x0, y0, x1, y1 = max(0, xs.min() - 4), max(0, ys.min() - 4), min(im.shape[1], xs.max() + 5), min(im.shape[0], ys.max() + 5)
out = im[y0:y1, x0:x1].astype(np.uint8); Image.fromarray(out, "RGBA").save(os.path.join(R, "assets/v20/narrator_skeleton_rock.png"), optimize=True)
low = int(np.where((out[..., 3] > 40).any(axis=1))[0].max()); cols = np.where(out[..., 3] > 40)[1]
# skull (measured by eye on the source at 2x: cheekbone to cheekbone 178 px, cranium top y 162 in source px)
SK = {"w": 178, "top": int(162 - y0), "cx": int(905 - x0)}
d = {"img": "assets/v20/narrator_skeleton_rock.png", "size": [int(out.shape[1]), int(out.shape[0])], "anchor": [int((cols.min() + cols.max()) // 2), int(low + 1)],
     "skull": SK, "source": "incoming/magnus_art/narrator_skeleton_rock.png", "crop": [int(x0), int(y0), int(x1), int(y1)]}
open(os.path.join(R, "src/config/narrator.js"), "w").write("// GENERATED by tools/import_narrator.py (Magnus's skeleton narrator on his rock).\nwindow.KM_NARRATOR = " + json.dumps(d) + ";\n")
print(d)
