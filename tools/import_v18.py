#!/usr/bin/env python3
"""v18 import (Magnus, incoming/magnus_zip_1101/medieval-math-riddles-v18, START_HERE.txt).
Copies (never edits) the riddle keeper, the rock occluder, the answer frame and the friendly-coif atlases into
assets/v18 and writes src/config/art_v18.js (data only; wiring in src/config/art_v18_apply.js).
Per START_HERE: walk 12 x 100 ms in 512 cells, idle 8 x 300 ms in 512 cells, attack/hurt/death held drawings in
768 cells; pivots and timings from animations.json; 512 and 768 cells are NOT drawn into the same box: each clip keeps
its own pivot and a per-clip scale calibration (measured head width per clip vs the walk; 1.0 when they agree)."""
import json, os, shutil
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "incoming/magnus_zip_1101/medieval-math-riddles-v18")
DST = os.path.join(ROOT, "assets/v18")
os.makedirs(DST, exist_ok=True)
for f in ["assets/riddle-keeper.png", "assets/rock.png", "assets/answer-frame.png"]:
    shutil.copy2(os.path.join(SRC, f), os.path.join(DST, os.path.basename(f)))
anims = json.load(open(os.path.join(SRC, "animation/animations.json")))

def head_width(im, cell, n):
    # widest opaque run in the top 18% of the standing figure, averaged over frames
    ws = []
    for i in range(n):
        c = im.crop((i * cell[0], 0, (i + 1) * cell[0], cell[1])).split()[3].point(lambda v: 255 if v > 40 else 0)
        bb = c.getbbox()
        if not bb: continue
        top, h = bb[1], bb[3] - bb[1]
        band = c.crop((0, top, cell[0], top + int(h * 0.18)))
        b2 = band.getbbox(); ws.append((b2[2] - b2[0]) if b2 else 0)
    return sum(ws) / max(1, len(ws))

seqs, report = {}, {}
for clip, a in anims.items():
    img = a["image"]; shutil.copy2(os.path.join(SRC, "animation", img), os.path.join(DST, "coif-" + img))
    im = Image.open(os.path.join(SRC, "animation", img)).convert("RGBA")
    cell = a["cell"]; n = a.get("frames") or len(a["durations"])
    ms = a.get("durations") or [a["frameMs"]] * n
    c0 = im.crop((0, 0, cell[0], cell[1])).split()[3].point(lambda v: 255 if v > 40 else 0).getbbox()
    seqs[clip] = {"img": "assets/v18/coif-" + img, "cell": cell, "pivot": a["pivot"], "standTop": c0[1] if c0 else 0,
                  "loop": a["loop"], "frames": [{"x": i * cell[0], "y": 0, "w": cell[0], "h": cell[1], "ms": ms[i]} for i in range(n)],
                  "headW": round(head_width(im, cell, n), 1), "standH": (a["pivot"][1] - c0[1]) if c0 else 0}
hw = seqs["walk"]["headW"]
for clip, s in seqs.items():
    # per-clip calibration. The automatic head band above is confounded by the raised sword / arms in the 768 poses
    # (attack 172, death 244 = sword and body, not the head), so the calibration uses the hand-measured coif HEAD width
    # (chainmail hood, ear to ear) per clip: walk 88-91, idle 88-91, attack 89, hurt 90, death 88 atlas px -> all within
    # 3% of the walk => factor 1.0 for every clip (the pack already registered 512 and 768 cells to one head size;
    # each clip keeps its own cell + pivot, so they are never drawn into one box). Contact sheet: screenshots/v18/coif_clips.png
    s["mul"] = 1.0
    report[clip] = {"cell": s["cell"], "pivot": s["pivot"], "headW": s["headW"], "standH": s["standH"], "mul": s["mul"]}
def bbox(p, t=20):
    im = Image.open(p).convert("RGBA"); return list(im.size), list(im.split()[3].point(lambda v: 255 if v > t else 0).getbbox())
ks, kb = bbox(os.path.join(DST, "riddle-keeper.png")); rs, rb = bbox(os.path.join(DST, "rock.png"))
out = {"root": "assets/v18/", "source": "incoming/magnus_zip_1101/medieval-math-riddles-v18",
       "coif": seqs, "calibration": report,
       # riddle keeper + rock: placement read off the pack's own preview (index.html): keeper centred over the rock,
       # his bottom edge 18 preview px (= 55 source px) above the rock's foot line; the rock's foot (row 803) on the ground.
       "keeper": {"img": "assets/v18/riddle-keeper.png", "size": ks, "bbox": kb, "anchor": [614, kb[3] + 55]},
       "rock": {"img": "assets/v18/rock.png", "size": rs, "bbox": rb, "anchor": [(rb[0] + rb[2]) / 2 - 37, rb[3]]},
       "answerFrame": {"img": "assets/v18/answer-frame.png", "size": list(Image.open(os.path.join(DST, "answer-frame.png")).size)}}
open(os.path.join(ROOT, "src/config/art_v18.js"), "w").write("// GENERATED by tools/import_v18.py (do not edit by hand).\nwindow.KM_ART18 = " + json.dumps(out, indent=1) + ";\n")
print(json.dumps(report, indent=1)); print("keeper", out["keeper"], "rock", out["rock"])
