# v11b: Magnus's riddle frame (riddle_frame.png, already on transparent): trimmed only. Drawn as a CSS border-image 9-slice:
# the two corner halves (each with its whole line segment) keep their pixels at ONE uniform scale; only the empty middle
# columns (no ink) stretch to fit the riddle, and there is no vertical stretch (the side ornaments span the full height).
if os.path.exists(ROOT + "/incoming/magnus_art/riddle_frame.png"):
    rf = trim("riddle_frame.png", "riddle-frame.png")
    fa = np.asarray(Image.open(OUT + "riddle-frame.png"))[..., 3] > 0; W_ = fa.shape[1]; mid = W_ // 2; assert fa[:, mid].sum() == 0
    l_ = mid; r_ = mid
    while l_ > 0 and fa[:, l_ - 1].sum() == 0: l_ -= 1
    while r_ < W_ - 1 and fa[:, r_ + 1].sum() == 0: r_ += 1
    rf["slice"] = [int(l_), int(W_ - r_ - 1)]  # the ink-free middle run is columns l_..r_  # left / right corner widths (source px), ink-free between
    art["riddleFrame"] = rf
    open(ROOT + "/src/config/art_v11.js", "w").write("// generated by tools/import_v11.py: Magnus's painted speech bubbles (exact source px; drawn x artScale) + purse + clouds + birds + full-screen scenes + spell icon + scroll stall/seller + divider + seated poses + riddle frame\nwindow.KM_ART11 = " + json.dumps(art, indent=2) + ";\n")
    print("riddleFrame", rf["size"], rf["slice"])

