#!/usr/bin/env python3
"""v11b: Magnus's painted speech bubbles from the handoff (animation-pack-v2 UI sheet, catalog ids ui-0 "Speech left"
and ui-1 "Speech right") copied byte-for-byte into assets/v11/ui/, plus their measured geometry -> src/config/art_v11.js.
Nothing is redrawn or resized: the game draws them at source px x KM_LAYOUT.artScale (the one global factor).
  tip  = the tail's lowest opaque point (where the bubble points at the speaker)
  text = a safe box inside the pale parchment interior (measured, inset ~12 src px from the ink border)"""
import json, shutil, os
import numpy as np
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = ROOT + "/incoming/medieval_math_handoff/MedievalMath-Handoff/output/medieval-math-animation-pack-v2/art/sprites/"
OUT = ROOT + "/assets/v11/ui/"
os.makedirs(OUT, exist_ok=True)
art = {"root": "assets/v11/ui/", "bubbles": {}}
for sid, name, side in (("ui-0", "speech-left.png", "left"), ("ui-1", "speech-right.png", "right")):
    shutil.copyfile(SRC + sid + ".png", OUT + name)
    im = np.array(Image.open(OUT + name).convert("RGBA")).astype(int); a = im[..., 3]; h, w = a.shape
    rows = np.where(a.max(1) > 128)[0]; yb = int(rows.max()); tipx = float(np.where(a[yb] > 128)[0].mean())
    lum = im[..., :3].mean(2); pale = (lum > 200) & (a > 250)
    widths = (a > 128).sum(1); body = [y for y in range(h) if widths[y] > 0.6 * widths.max()]
    cy = (body[0] + body[-1]) // 2; xs = np.where(pale[cy])[0]; ys = np.where(pale[:, w // 2])[0]
    ins = 12
    art["bubbles"][side] = {"img": name, "source": "medieval-math-animation-pack-v2/art/sprites/" + sid + ".png", "size": [w, h],
        "tip": [round(tipx, 1), yb], "text": [int(xs.min()) + ins, int(ys.min()) + ins, int(xs.max() - xs.min()) - 2 * ins, int(ys.max() - ys.min()) - 2 * ins]}
open(ROOT + "/src/config/art_v11.js", "w").write("// generated by tools/import_v11.py: Magnus's painted speech bubbles (exact source px; drawn x artScale)\nwindow.KM_ART11 = " + json.dumps(art, indent=2) + ";\n")
print(json.dumps(art, indent=1))

# v11b: Magnus's painted money purse (incoming/magnus_art/money_purse.png, 1254x1254 RGBA). Its background is ALREADY
# transparent (no white to remove); it is only trimmed to the painted pixels (alpha >= 16, +8 px margin) and the 155 stray
# alpha-1 pixels outside the bag are cleared. Pixels are not resampled here; the HUD shows it at the hearts' height.
P = ROOT + "/incoming/magnus_art/money_purse.png"
if os.path.exists(P):
    im = Image.open(P).convert("RGBA"); a = np.array(im); al = a[..., 3]
    ys, xs = np.where(al >= 16); x0, y0, x1, y1 = xs.min() - 8, ys.min() - 8, xs.max() + 9, ys.max() + 9
    a[al < 16] = 0
    out = Image.fromarray(a).crop((x0, y0, x1, y1)); out.save(OUT + "money-purse.png")
    art["purse"] = {"img": "money-purse.png", "source": "incoming/magnus_art/money_purse.png", "size": list(out.size), "crop": [int(x0), int(y0), int(x1), int(y1)]}
    open(ROOT + "/src/config/art_v11.js", "w").write("// generated by tools/import_v11.py: Magnus's painted speech bubbles (exact source px; drawn x artScale) + money purse\nwindow.KM_ART11 = " + json.dumps(art, indent=2) + ";\n")
    print("purse", art["purse"])

# v11b: Magnus's painted clouds (incoming/magnus_art/clouds_sheet_6.png, 1536x1024, six ink clouds in 2 columns x 3 rows).
# The sheet is ALREADY ink on transparent (no white to key out). Each cell is trimmed to its painted pixels (alpha >= 8,
# +6 px margin), faint alpha < 8 specks are cleared; pixels are never resampled (drawn at source px x artScale).
P = ROOT + "/incoming/magnus_art/clouds_sheet_6.png"
if os.path.exists(P):
    a = np.array(Image.open(P).convert("RGBA")); H, Wd = a.shape[:2]; a[a[..., 3] < 8] = 0
    clouds = []
    for r in range(3):
        for c in range(2):
            y0, y1, x0, x1 = r * H // 3, (r + 1) * H // 3, c * Wd // 2, (c + 1) * Wd // 2
            cell = a[y0:y1, x0:x1]; ys, xs = np.where(cell[..., 3] > 0)
            bx0, by0, bx1, by1 = max(0, xs.min() - 6), max(0, ys.min() - 6), min(cell.shape[1], xs.max() + 7), min(cell.shape[0], ys.max() + 7)
            name = "cloud-%d.png" % (len(clouds) + 1)
            Image.fromarray(cell[by0:by1, bx0:bx1]).save(OUT + name)
            clouds.append({"img": name, "size": [int(bx1 - bx0), int(by1 - by0)], "cell": [r, c], "crop": [int(x0 + bx0), int(y0 + by0), int(x0 + bx1), int(y0 + by1)]})
    art["clouds"] = clouds; art["cloudsSource"] = "incoming/magnus_art/clouds_sheet_6.png"
    open(ROOT + "/src/config/art_v11.js", "w").write("// generated by tools/import_v11.py: Magnus's painted speech bubbles (exact source px; drawn x artScale) + money purse + clouds\nwindow.KM_ART11 = " + json.dumps(art, indent=2) + ";\n")
    print("clouds", [(c["img"], c["size"]) for c in clouds])

# v11b: Magnus's painted birds (incoming/magnus_art/birds_sheet_8.png, 1774x887): 2 rows x 4 frames (wings up -> level),
# bottom row a smaller bird. ALREADY ink on transparent. Every frame of a row is cut with the SAME box (the row's union of
# painted pixels in cell coordinates, +6 px) so the body stays put between frames; specks with alpha < 8 cleared. No resampling.
P = ROOT + "/incoming/magnus_art/birds_sheet_8.png"
if os.path.exists(P):
    a = np.array(Image.open(P).convert("RGBA")); H, Wd = a.shape[:2]; a[a[..., 3] < 8] = 0
    birds = []
    for r in range(2):
        cells = [a[r * H // 2:(r + 1) * H // 2, c * Wd // 4:(c + 1) * Wd // 4] for c in range(4)]
        boxes = [np.where(cl[..., 3] > 0) for cl in cells]
        x0 = max(0, min(b[1].min() for b in boxes) - 6); y0 = max(0, min(b[0].min() for b in boxes) - 6)
        x1 = min(cells[0].shape[1], max(b[1].max() for b in boxes) + 7); y1 = min(cells[0].shape[0], max(b[0].max() for b in boxes) + 7)
        frames = []
        for c, cl in enumerate(cells):
            name = "bird-%s-%d.png" % ("ab"[r], c + 1); Image.fromarray(cl[y0:y1, x0:x1]).save(OUT + name); frames.append(name)
        birds.append({"frames": frames, "size": [int(x1 - x0), int(y1 - y0)], "row": r})
    art["birds"] = birds; art["birdsSource"] = "incoming/magnus_art/birds_sheet_8.png"
    open(ROOT + "/src/config/art_v11.js", "w").write("// generated by tools/import_v11.py: Magnus's painted speech bubbles (exact source px; drawn x artScale) + money purse + clouds + birds\nwindow.KM_ART11 = " + json.dumps(art, indent=2) + ";\n")
    print("birds", [(b["frames"][0], b["size"]) for b in birds])

# v11b: Magnus's FULL-SCREEN scenes (painted to fill the screen; a floor/ground ink line, parchment below it).
#  tavern-interior = incoming/magnus_art/tavern_interior_fullscreen.png (3532x1762) - the new tavern interior
#  tavern-arrival  = incoming/magnus_art/reference_tavern_fullscreen.png (3512x1764) - the tavern exterior on arrival
# Paper graded to the strip parchment (per-channel gain: this image's paper median -> the graded parchment's median, the
# same kind of grade as tools/import_v10.py), alpha dropped (fully opaque in the source), saved as optimised PNG (lossless).
# floorRow = the measured ink line under the floor; the game puts it on its ground line (one uniform scale, no stretch).
par = np.asarray(Image.open(ROOT + "/assets/v10/paper/parchment.png").convert("RGB")).reshape(-1, 3)
target = np.median(par[par.sum(1) > 450], 0)
scenes = {}
for sid, src, floor in [("tavern-interior", "tavern_interior_fullscreen.png", 1195), ("tavern-arrival", "reference_tavern_fullscreen.png", 1203)]:
    P = ROOT + "/incoming/magnus_art/" + src
    if not os.path.exists(P): continue
    a = np.asarray(Image.open(P).convert("RGB")).astype(np.float32); H = a.shape[0]
    below = a[int(floor + 0.06 * H):].reshape(-1, 3); paper = np.median(below[below.sum(1) > 450], 0)
    gain = target / paper; out = np.clip(a * gain, 0, 255).round().astype(np.uint8)
    name = "scene-" + sid + ".png"; Image.fromarray(out).save(OUT + name, optimize=True, compress_level=9)
    scenes[sid] = {"img": name, "source": "incoming/magnus_art/" + src, "size": [int(a.shape[1]), int(H)], "floorRow": floor, "gain": [round(float(g), 4) for g in gain], "bytes": os.path.getsize(OUT + name), "srcBytes": os.path.getsize(P)}
# v11b fix: reference_tavern_fullscreen.png carries its OWN painted divider (rows 1198-1206, centre 1201) about 38 px under
# its painted ground (grass ink ends ~1163). Row 1203 was that divider, so the party stood on it. Now the painted divider
# lands exactly on our divider (ground 655.33 stage px + 26.5 gap) and the scene is clipped above it (clipRow), so only one
# divider shows. floorRow = 1201 x 655.33 / 681.83.
if "tavern-arrival" in scenes:
    scenes["tavern-arrival"].update(paintedDividerRow=1201, floorRow=round(1201 * 655.33 / (655.33 + 26.5), 1), clipRow=1190)
art["scenes"] = scenes
open(ROOT + "/src/config/art_v11.js", "w").write("// generated by tools/import_v11.py: Magnus's painted speech bubbles (exact source px; drawn x artScale) + purse + clouds + birds + full-screen scenes\nwindow.KM_ART11 = " + json.dumps(art, indent=2) + ";\n")
print("scenes", json.dumps(scenes))

# v11b: Magnus's Spell of Stupidity icon, scroll seller and scroll stall. All three are ALREADY ink/paint on transparent
# (no white box to remove): trimmed to the painted pixels (alpha >= 8, +6 px), faint specks (alpha < 8) cleared, no resampling.
def trim(src, name):
    a = np.asarray(Image.open(ROOT + "/incoming/magnus_art/" + src).convert("RGBA")).copy(); a[a[..., 3] < 8] = 0
    ys, xs = np.where(a[..., 3] > 0); x0, y0 = max(0, xs.min() - 6), max(0, ys.min() - 6); x1, y1 = min(a.shape[1], xs.max() + 7), min(a.shape[0], ys.max() + 7)
    Image.fromarray(a[y0:y1, x0:x1]).save(OUT + name, optimize=True)
    return {"img": name, "source": "incoming/magnus_art/" + src, "size": [int(x1 - x0), int(y1 - y0)], "crop": [int(x0), int(y0), int(x1), int(y1)]}
if os.path.exists(ROOT + "/incoming/magnus_art/spell_stupidity_icon.png"):
    art["spellIcon"] = trim("spell_stupidity_icon.png", "spell-stupidity.png")
if os.path.exists(ROOT + "/incoming/magnus_art/scroll_stall.png") and os.path.exists(ROOT + "/incoming/magnus_art/scroll_seller.png"):
    st, se = trim("scroll_stall.png", "scroll-stall.png"), trim("scroll_seller.png", "scroll-seller.png")
    # Sizes from Magnus's reference_scroll_stall.png (1598x788), measured against the knight there:
    #  knight 283 ref px tall (helmet 351 -> feet 634); stall 501 ref px tall (post tops 137 -> legs 638), 741 wide (722..1463);
    #  seller: hat tip at ref y 293, his held scroll at ref y 410 (117 ref px) = 448 source px in scroll_seller.png;
    #  the scroll end of his reach at ref x 995. Our knight stands 355 stage px (hero source px x artScale 0.6), so
    #  stage px per ref px = 355 / 283 = 1.254.
    REF_KNIGHT, HERO_STAGE = 283.0, 355.2; k = HERO_STAGE / REF_KNIGHT
    st["scale"] = round(501.0 * k / st["size"][1], 4)                 # stage px per stall source px
    se["scale"] = round(117.0 / 448.0 * k, 4)                          # stage px per seller source px
    se["at"] = [round((995 - 722) / 741.0, 4), round((293 - 137) / 501.0, 4)]  # his left edge / hat top in stall-relative units
    art["stall"] = {"stall": st, "seller": se, "ref": "incoming/magnus_art/reference_scroll_stall.png"}
    print("stall", st["scale"], "seller", se["scale"], "x artScale:", round(st["scale"] / 0.6, 3), round(se["scale"] / 0.6, 3))
open(ROOT + "/src/config/art_v11.js", "w").write("// generated by tools/import_v11.py: Magnus's painted speech bubbles (exact source px; drawn x artScale) + purse + clouds + birds + full-screen scenes + spell icon + scroll stall/seller\nwindow.KM_ART11 = " + json.dumps(art, indent=2) + ";\n")

# v11b: Magnus's divider line (incoming/magnus_art/divider_line.png, 2172x724, ALREADY on transparent): trimmed to its ink
