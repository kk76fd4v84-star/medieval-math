P = ROOT + "/incoming/magnus_art/divider_line.png"
if os.path.exists(P):
    a = np.asarray(Image.open(P).convert("RGBA")).copy(); al = a[..., 3]; a[al < 8] = 0
    ys, xs = np.where(a[..., 3] >= 32); x0, y0, x1, y1 = xs.min() - 6, ys.min() - 6, xs.max() + 7, ys.max() + 7
