#!/usr/bin/env python3
"""assets/audio_map.json -> src/config/audio_map.js (window.KM_AUDIO_MAP) so sound + voice-over also work when the game
is opened from file:// (browsers refuse fetch() of local json there; a <script> loads fine). Re-run after editing the json."""
import json, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
m = json.load(open(os.path.join(R, "assets/audio_map.json")))
open(os.path.join(R, "src/config/audio_map.js"), "w").write("// GENERATED by tools/build_audio_map.py from assets/audio_map.json (edit the json, then re-run).\nwindow.KM_AUDIO_MAP = " + json.dumps(m, indent=1, ensure_ascii=False) + ";\n")
missing = [f for k, v in m.items() if isinstance(v, dict) for f in v.get("files", []) if not os.path.exists(os.path.join(R, "assets/audio", f))]
print("events", len([k for k in m if not k.startswith("_")]), "missing files", missing)
